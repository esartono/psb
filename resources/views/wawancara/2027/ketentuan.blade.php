    <li>Ketentuan Khusus Potongan Biaya Penerimaan Murid Baru
        <ol class="biasa">
            <li>Ketentuan potongan khusus hanya berlaku jika pembayaran dilakukan lunas di rentang waktu pelunasan biaya daftar ulang (<b>30 hari setelah pengumuman</b>)</li>
            <li><b>Dana Pengembangan</b> yang digunakan untuk <b>perhitungan diskon khusus adalah setelah dikurangi potongan umum pada ketentuan umum.</b></li>
            <li>Ketentuan potongan khusus yang satu tidak dapat digabung dengan jenis potongan khusus lainnya</li>
            <div class="page-break"></div>
            <li>Jenis Potongan Khusus sebagai berikut:
                <ol class="step1a">
                    <li>
                        Potongan Saudara Kandung
                        <ol class="step2">
                            <li>Potongan dana pengembangan bagi calon peserta didik yang memiliki saudara &nbsp; &nbsp; kandung yang sedang bersekolah di Nurul Fikri Islamic School, sebagai berikut:
                                <ol class="step3">
                                    <li>Saudara kandung pertama mendapatkan potongan 5% dari Dana Pengembangan</li>
                                    <li>Saudara kandung kedua dan seterusnya mendapatkan potongan 10% dari Dana Pengembangan</li>
                                </ol>
                            </li>
                            <li>Potongan Dana Pengembangan bagi orangtua calon peserta didik yang mendaftarkan (sampai dengan daftar ulang lunas) lebih dari 1 calon peserta didik pada tahun pelajaran yang sama di Nurul Fikri Islamic School, masing-masing calon peserta didik mendapatkan potongan sebesar 10% dari Dana Pengembangan.</li>
                        </ol>
                    </li>
                    <li>Potongan Internal
                        <ol class="step2">
                            <li>Potongan biaya sebesar Rp. 5.000.000 dari dana pengembangan, bagi Pendaftar SDIT Nurul Fikri yang berasal dari TKIT Nurul Fikri.</li>
                            <li>Potongan biaya sebesar 10% dari dana pengembangan bagi calon peserta didik berasal dari Nurul Fikri Islamic School dan NFBS Bogor.</li>
                        </ol>
                    </li>
                    <li>Potongan Prestasi
                        <ol class="step2">
                            <li>Potongan biaya 25% dari Dana Pengembangan dan bebas biaya pendaftaran bagi &nbsp; &nbsp; &nbsp; &nbsp; calon peserta didik yang berasal dari Nurul Fikri Islamic School dan NFBS Bogor yang mendapatkan undangan khusus dari Direktorat Pendidikan Nurul Fikri Islamic School.</li>
                            <li>Potongan biaya 50% dari Dana Pengembangan bagi calon peserta didik Pemenang Lomba Tingkat Nasional (Berjenjang) Juara 1 dan 2 yang tercatat dalam Pusat Prestasi Nasional Kementrian terkait, dibuktikan dengan sertifikat dan diverifikasi oleh panitia.</li>
                            <li>Potongan biaya sebesar 15% dari Dana Pengembangan bagi calon peserta didik yang memiliki hafalan Al-Qur’an, sebagai berikut:
                                <ol class="step3">
                                    <li>Pendaftar SD minimal 4 juz</li>
                                    <li>Pendaftar SMP minimal 8 juz</li>
                                    <li>Bagi siswa Pendaftar SMA minimal 10 juz</li>
                                </ol>
                            </li>
                            <li>Potongan biaya sebesar 50% dari Dana Pengembangan bagi calon peserta didik yang memiliki hafalan Al-Qur’an minimal 15 Juz dan sudah diverifikasi oleh Nurul Fikri Islamic School.</li>
                        </ol>
                    </li>
                    <li><b>Ketentuan khusus potongan biaya penerimaan siswa baru tidak bersifat akumulatif</b></li>
                    <li><b>Hasil keputusan panitia PPDB tidak dapat diganggu gugat</b></li>
                </ol>
            </li>
        </ol>
